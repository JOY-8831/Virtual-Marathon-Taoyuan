let currentLang = 'zh';

document.addEventListener('DOMContentLoaded', () => {
    // Language Toggle Logic
    const langToggleBtn = document.getElementById('lang-toggle');
    langToggleBtn.addEventListener('click', () => {
        currentLang = currentLang === 'zh' ? 'en' : 'zh';
        langToggleBtn.textContent = currentLang === 'zh' ? 'EN' : '中文';
        
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[currentLang][key]) {
                // If it contains HTML (like <br>), use innerHTML, else textContent
                if (translations[currentLang][key].includes('<br>') || translations[currentLang][key].includes('<strong>')) {
                    el.innerHTML = translations[currentLang][key];
                } else {
                    el.textContent = translations[currentLang][key];
                }
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (translations[currentLang][key]) {
                el.placeholder = translations[currentLang][key];
            }
        });
    });

    // Navbar Scroll Effect
    const navbar = document.querySelector('.navbar');
    
    window.addEventListener('scroll', () => {
        if (window.scrollY > 50) {
            navbar.classList.add('scrolled');
        } else {
            navbar.classList.remove('scrolled');
        }
    });

    // Mobile Menu Toggle
    const hamburger = document.querySelector('.hamburger');
    const navLinks = document.querySelector('.nav-links');

    hamburger.addEventListener('click', () => {
        hamburger.classList.toggle('active');
        navLinks.classList.toggle('active');
    });

    // Close menu when clicking a link
    document.querySelectorAll('.nav-links a').forEach(link => {
        link.addEventListener('click', () => {
            hamburger.classList.remove('active');
            navLinks.classList.remove('active');
        });
    });

    // Strava File Upload Interaction
    const dropZone = document.getElementById('drop-zone');
    const fileInput = document.getElementById('screenshot');
    const previewContainer = document.getElementById('preview-container');

    dropZone.addEventListener('click', () => fileInput.click());

    dropZone.addEventListener('dragover', (e) => {
        e.preventDefault();
        dropZone.classList.add('dragover');
    });

    dropZone.addEventListener('dragleave', () => {
        dropZone.classList.remove('dragover');
    });

    dropZone.addEventListener('drop', (e) => {
        e.preventDefault();
        dropZone.classList.remove('dragover');
        
        if (e.dataTransfer.files.length) {
            fileInput.files = e.dataTransfer.files;
            handleFileUpload(fileInput.files);
        }
    });

    fileInput.addEventListener('change', () => {
        if (fileInput.files.length) {
            handleFileUpload(fileInput.files);
        }
    });

    function handleFileUpload(files) {
        previewContainer.innerHTML = '';
        let validCount = 0;
        
        Array.from(files).forEach(file => {
            if (!file.type.startsWith('image/')) {
                return;
            }
            validCount++;
            const reader = new FileReader();
            reader.onload = (e) => {
                const img = document.createElement('img');
                img.src = e.target.result;
                img.alt = 'Preview';
                previewContainer.appendChild(img);
            };
            reader.readAsDataURL(file);
        });

        if (validCount === 0) {
            alert(currentLang === 'en' ? 'Please upload an image file!' : '請至少上傳一張圖片檔案！');
        } else {
            const textSpan = dropZone.querySelector('span');
            if (currentLang === 'zh') {
                textSpan.textContent = `已選擇 ${validCount} 張圖片`;
            } else {
                textSpan.textContent = `${validCount} image(s) selected`;
            }
        }
    }

    // Strava Form Submit Mockup
    const stravaForm = document.getElementById('strava-form');
    const successMessage = document.getElementById('success-message');
    const resetBtn = document.getElementById('reset-btn');

    stravaForm.addEventListener('submit', (e) => {
        e.preventDefault();
        
        // Mocking an API call
        const btn = stravaForm.querySelector('button[type="submit"]');
        const originalText = btn.textContent;
        btn.textContent = currentLang === 'en' ? 'Uploading...' : '上傳中...';
        btn.disabled = true;

        setTimeout(() => {
            stravaForm.classList.add('hidden');
            successMessage.classList.remove('hidden');
            btn.textContent = originalText;
            btn.disabled = false;
        }, 1500);
    });

    resetBtn.addEventListener('click', () => {
        stravaForm.reset();
        previewContainer.innerHTML = '';
        const textSpan = dropZone.querySelector('span');
        textSpan.textContent = translations[currentLang].strava_upload_text;
        successMessage.classList.add('hidden');
        stravaForm.classList.remove('hidden');
    });
});
